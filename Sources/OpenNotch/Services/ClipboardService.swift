import AppKit

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String?
    let image: NSImage?
    let date = Date()

    static func == (a: ClipItem, b: ClipItem) -> Bool { a.id == b.id }
}

/// Clipboard history kept in memory only (never written to disk).
/// macOS has no clipboard-change notification, so we compare `changeCount` twice a
/// second — a single integer read, with a generous timer tolerance for coalescing.
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    private let limit = 40
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard Settings.bool(Settings.clipboardHistory) else { return }

        // Respect apps (password managers) that mark entries as concealed or transient.
        let types = pb.types ?? []
        let skip = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                    "org.nspasteboard.AutoGeneratedType"]
        if types.contains(where: { skip.contains($0.rawValue) }) { return }

        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if items.first?.text == text { return }
            insert(ClipItem(text: text, image: nil))
        } else if types.contains(.png) || types.contains(.tiff), let image = NSImage(pasteboard: pb) {
            insert(ClipItem(text: nil, image: image))
        }
    }

    private func insert(_ item: ClipItem) {
        if let text = item.text { items.removeAll { $0.text == text } }
        items.insert(item, at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let text = item.text { pb.setString(text, forType: .string) }
        else if let image = item.image { pb.writeObjects([image]) }
        lastCount = pb.changeCount
        // Move it to the top.
        items.removeAll { $0 == item }
        items.insert(item, at: 0)
    }

    func remove(_ item: ClipItem) { items.removeAll { $0 == item } }
    func clear() { items.removeAll() }
}
